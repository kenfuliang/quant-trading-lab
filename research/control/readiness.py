"""Readiness checklist: a scored, evidence-linked registry with a pure loader and renderers.

`research/registry/readiness.json` is the one hand-maintained assessment. Each aspect carries a
0-5 score (half steps), an importance, the repository files that support the score and the gate
items it relates to. The loader validates shape and every evidence path and rejects unknown
gate references; the renderers are pure and deterministic (no clock: `updated` is the
registry's `assessed` date). Nothing here writes a file.

Rubric: 0 absent, 1 ad hoc or one-off, 2 partial, 3 works for the current scope,
4 robust and tested, 5 production-grade.
"""
import html
import json
import re
from pathlib import Path

from research.control.incumbents import _cell

SCHEMA = "readiness/v1"
AREAS = ("Data", "Research and evaluation", "Portfolio and risk", "Execution and operations",
         "Engineering", "People and process")
RUBRIC = ((0, "absent"), (1, "ad hoc or one-off"), (2, "partial"), (3, "works for the current scope"),
          (4, "robust and tested"), (5, "production-grade"))
WEIGHTS = {"H": 3, "M": 2, "L": 1}
OWNER = "project-maintainers"
GENERATED = "<!-- Generated by scripts/readiness.py render. Do not edit by hand. -->"
_FIELDS = {"id", "area", "aspect", "score", "importance", "critique", "next_action",
           "roadmap_step", "evidence", "gates"}
_TEXT = ("id", "aspect", "critique", "next_action")


class ReadinessError(ValueError):
    pass


def _is_number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _check_aspect(item, gate_ids, root, seen):
    if not isinstance(item, dict) or set(item) != _FIELDS:
        raise ReadinessError(f"bad aspect entry: {item!r}")
    ident = item["id"]
    for key in _TEXT:
        if not isinstance(item[key], str) or not item[key].strip():
            raise ReadinessError(f"{ident!r}: {key} must be non-empty text")
    if ident in seen:
        raise ReadinessError(f"aspect {ident} is declared twice")
    if item["area"] not in AREAS:
        raise ReadinessError(f"{ident}: unknown area {item['area']!r}")
    if item["importance"] not in WEIGHTS:
        raise ReadinessError(f"{ident}: importance must be one of H, M, L")
    score = item["score"]
    if not _is_number(score) or not 0 <= score <= 5 or score * 2 != int(score * 2):
        raise ReadinessError(f"{ident}: score must be 0 to 5 in half steps")
    step = item["roadmap_step"]
    if step is not None and (isinstance(step, bool) or not isinstance(step, int) or step < 1):
        raise ReadinessError(f"{ident}: roadmap_step must be null or a positive integer")
    for key in ("evidence", "gates"):
        values = item[key]
        if not isinstance(values, list) or not all(isinstance(v, str) and v for v in values):
            raise ReadinessError(f"{ident}: {key} must be a list of text")
    if not item["evidence"] and score > 1:
        raise ReadinessError(f"{ident}: a score above 1 needs at least one evidence path")
    base = Path(root).resolve()
    for rel in item["evidence"]:
        target = (base / rel).resolve()
        if Path(rel).is_absolute() or base not in target.parents or not target.is_file():
            raise ReadinessError(f"{ident}: evidence path {rel!r} is not a file under the repository")
    for gate in item["gates"]:
        if gate not in gate_ids:
            raise ReadinessError(f"{ident}: unknown gate reference {gate!r}")


def load_readiness(path, gate_ids, root):
    """The validated document. Raises ReadinessError on any shape or reference problem."""
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ReadinessError(f"readiness unreadable: {error}") from None
    if (not isinstance(doc, dict) or doc.get("schema") != SCHEMA or set(doc) != {"schema", "assessed", "aspects"}
            or not isinstance(doc["aspects"], list)):
        raise ReadinessError(f"readiness must have schema {SCHEMA}, assessed and an aspects list")
    if not isinstance(doc["assessed"], str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", doc["assessed"]):
        raise ReadinessError("assessed must be a YYYY-MM-DD date")
    seen = set()
    for item in doc["aspects"]:
        _check_aspect(item, gate_ids, root, seen)
        seen.add(item["id"])
    return doc


def _natural(ident):
    return [int(part) if part.isdigit() else part for part in re.split(r"(\d+)", ident)]


def fix_first(doc):
    """Importance H with score at most 2, lowest score first, then by id."""
    rows = [a for a in doc["aspects"] if a["importance"] == "H" and a["score"] <= 2]
    return sorted(rows, key=lambda a: (a["score"], _natural(a["id"])))


def _average(rows):
    simple = sum(a["score"] for a in rows) / len(rows)
    weight = sum(WEIGHTS[a["importance"]] for a in rows)
    return simple, sum(a["score"] * WEIGHTS[a["importance"]] for a in rows) / weight


def area_scores(doc):
    """(simple, weighted) average per populated area, plus `Overall` over every aspect."""
    scores = {}
    for area in AREAS:
        rows = [a for a in doc["aspects"] if a["area"] == area]
        if rows:
            scores[area] = _average(rows)
    if doc["aspects"]:
        scores["Overall"] = _average(doc["aspects"])
    return scores


def _by_area(doc):
    for area in AREAS:
        rows = sorted((a for a in doc["aspects"] if a["area"] == area), key=lambda a: _natural(a["id"]))
        if rows:
            yield area, rows


def _links(aspect):
    parts = [f"`{p}`" for p in aspect["evidence"]]
    return ", ".join(_cell(p) for p in parts) if parts else "none"


def render_markdown(doc):
    """The `docs/readiness.md` text. Pure: the date is the registry's `assessed` field."""
    out = [f"---\nstatus: active\nupdated: {doc['assessed']}\nowner: {OWNER}\n---\n\n"
           f"# Readiness checklist\n\n{GENERATED}\n\n"
           "A scored view of how ready each part of the platform is, assessed "
           f"{doc['assessed']} from `research/registry/readiness.json`. Scores are judgements "
           "tied to the evidence files listed per aspect, not measurements.\n",
           "## Rubric\n",
           *[f"- {score} {meaning}" for score, meaning in RUBRIC],
           "\nImportance is H, M or L, weighted 3, 2 and 1 in the weighted average. "
           "Half steps are allowed.\n",
           "## Area summary\n",
           "| Area | Aspects | Simple average | Weighted average |",
           "| --- | --- | --- | --- |"]
    scores = area_scores(doc)
    for area, rows in _by_area(doc):
        simple, weighted = scores[area]
        out.append(f"| {area} | {len(rows)} | {simple:.2f} | {weighted:.2f} |")
    if "Overall" in scores:
        simple, weighted = scores["Overall"]
        out.append(f"| Overall | {len(doc['aspects'])} | {simple:.2f} | {weighted:.2f} |")
    out += ["\n## Fix first\n",
            "Importance H with score 2 or lower, lowest score first.\n",
            "| Id | Aspect | Score | Next action | Roadmap step |",
            "| --- | --- | --- | --- | --- |"]
    for a in fix_first(doc):
        out.append(f"| {a['id']} | {_cell(a['aspect'])} | {a['score']:g} | {_cell(a['next_action'])} "
                   f"| {_step(a)} |")
    out.append("\n## All aspects\n")
    for area, rows in _by_area(doc):
        out += [f"### {area}\n",
                "| Id | Aspect | Score | Imp | Critique | Next action | Step | Gates | Evidence |",
                "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for a in rows:
            out.append("| " + " | ".join([
                a["id"], _cell(a["aspect"]), f"{a['score']:g}", a["importance"], _cell(a["critique"]),
                _cell(a["next_action"]), _step(a), _cell(", ".join(a["gates"]) or "none"), _links(a)]) + " |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def _step(aspect):
    return "-" if aspect["roadmap_step"] is None else str(aspect["roadmap_step"])


_CSS = """:root{--bg:#f6f7f9;--card:#fff;--ink:#14181f;--mute:#5b6573;--line:#dfe3e8;--acc:#2f6fdb}
@media (prefers-color-scheme:dark){:root{--bg:#0e1116;--card:#171b22;--ink:#e8ecf2;--mute:#9aa5b4;--line:#2a313c;--acc:#6aa0ff}}
*{box-sizing:border-box}body{margin:0;padding:16px;background:var(--bg);color:var(--ink);font:14px/1.4 system-ui,-apple-system,sans-serif}
h1{margin:0 0 4px}h2{margin:28px 0 8px}.muted{color:var(--mute)}
table{border-collapse:collapse;width:100%;background:var(--card);margin:6px 0 14px}
th,td{border:1px solid var(--line);padding:4px 8px;text-align:left;vertical-align:top}th{color:var(--mute);font-weight:600}
.bar{display:inline-block;height:8px;background:var(--acc);border-radius:4px;vertical-align:middle;margin-right:6px}"""


def _e(value):
    return html.escape(str(value))


def _table(head, rows):
    cells = "".join(f"<th>{_e(h)}</th>" for h in head)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows)
    return f"<table><thead><tr>{cells}</tr></thead><tbody>{body}</tbody></table>"


def _bar(score):
    return f'<span class="bar" style="width:{int(score * 16)}px"></span>{_e(f"{score:g}")}'


def render_page(doc, built):
    """A standalone HTML page of the checklist. Every value is passed through html.escape."""
    scores = area_scores(doc)
    summary = [[_e(area), _e(len(rows)), _e(f"{scores[area][0]:.2f}"), _e(f"{scores[area][1]:.2f}")]
               for area, rows in _by_area(doc)]
    if "Overall" in scores:
        summary.append(["<strong>Overall</strong>", _e(len(doc["aspects"])),
                        _e(f"{scores['Overall'][0]:.2f}"), _e(f"{scores['Overall'][1]:.2f}")])
    fix = [[_e(a["id"]), _e(a["aspect"]), _bar(a["score"]), _e(a["next_action"]), _e(_step(a))]
           for a in fix_first(doc)]
    sections = []
    for area, rows in _by_area(doc):
        sections.append(f"<h3>{_e(area)}</h3>" + _table(
            ["Id", "Aspect", "Score", "Imp", "Critique", "Next action", "Step", "Gates", "Evidence"],
            [[_e(a["id"]), _e(a["aspect"]), _bar(a["score"]), _e(a["importance"]), _e(a["critique"]),
              _e(a["next_action"]), _e(_step(a)), _e(", ".join(a["gates"]) or "none"),
              _e(", ".join(a["evidence"]) or "none")] for a in rows]))
    rubric = "".join(f"<li>{_e(score)} {_e(meaning)}</li>" for score, meaning in RUBRIC)
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>Readiness checklist</title><style>{_CSS}</style></head><body>"
            f"<h1>Readiness checklist</h1><p class=\"muted\">Assessed {_e(doc['assessed'])}; "
            f"built {_e(built)}. Scores are judgements tied to the listed evidence.</p>"
            f"<h2>Rubric</h2><ul>{rubric}</ul>"
            f"<h2>Area summary</h2>{_table(['Area', 'Aspects', 'Simple average', 'Weighted average'], summary)}"
            f"<h2>Fix first</h2>{_table(['Id', 'Aspect', 'Score', 'Next action', 'Roadmap step'], fix)}"
            f"<h2>All aspects</h2>{''.join(sections)}</body></html>\n")
