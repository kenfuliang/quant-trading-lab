"""Pure renderers over registry records: leaderboard, dead ends, learning curve.

No file access except an injected `link_ok(path)` used to decide whether a reference
becomes a link. Output is deterministic for the same records, so a stale generated
file is detectable by string comparison. Ranking never blends metrics: within one
evidence class and comparison context, a record is on the frontier unless another
has net CAGR at least as high and drawdown at most as high, with one strictly better.
Equality is a tie. Development rows are viewed history; only forward, shadow, paper
and live classes can show learning that is not hindsight.
"""
from research.control.experiment_registry import CLASSES, DRAWDOWN_TOLERANCE

OWNER = "research-maintainers"
CLASS_TITLES = {
    "live": "Live", "paper": "Paper", "shadow": "Shadow (hypothetical positions, no orders)",
    "sealed_forward": "Sealed forward window", "development": "Development (viewed history)"}


def _cell(text):
    return str(text).replace("|", "/").replace("\n", " ").strip()


def _pct(value, digits=2):
    return "n/a" if value is None else f"{value * 100:.{digits}f}%"


def _num(value, digits=2):
    return "n/a" if value is None else f"{value:.{digits}f}"


def _underwater(metrics):
    sessions, days = metrics.get("longest_underwater_sessions"), metrics.get("longest_underwater_days")
    return "n/a" if sessions is None and days is None else f"{sessions if sessions is not None else '?'} / {days if days is not None else '?'}"


def frontier_ids(records):
    """Record ids on the net CAGR (max) versus max drawdown (min) frontier, ties kept."""
    scored = [r for r in records if r["metrics"].get("net_cagr") is not None
              and r["metrics"].get("max_drawdown") is not None]

    def dominates(a, b):
        ma, mb = a["metrics"], b["metrics"]
        return (ma["net_cagr"] >= mb["net_cagr"] and ma["max_drawdown"] <= mb["max_drawdown"]
                and (ma["net_cagr"] > mb["net_cagr"] or ma["max_drawdown"] < mb["max_drawdown"]))
    return {r["record_id"] for r in scored if not any(dominates(o, r) for o in scored if o is not r)}


def updated_date(records):
    return max((r["logged_at"][:10] for r in records), default="2026-01-01")


def _front(title, records, intro):
    return (f"---\nstatus: active\nupdated: {updated_date(records)}\nowner: {OWNER}\n---\n\n"
            f"# {title}\n\n<!-- Generated by scripts/experiments.py render. Do not edit by hand. -->\n\n{intro}\n")


def _ref(label, path, link_ok):
    if not path:
        return None
    if link_ok is not None and link_ok(path):
        return f"[{label}]({path})"
    return f"{label} `{_cell(path)}`"


def _evidence(record, link_ok):
    refs = record.get("refs") or {}
    parts = [_ref("Study", refs.get("study"), link_ok), _ref("Receipt", refs.get("receipt"), link_ok)]
    trial = refs.get("ledger_trial")
    if trial:
        parts.append(f"trial {trial.get('cycle_id')}#{trial.get('trial_number')}")
    return " · ".join(p for p in parts if p) or "none"


def render_leaderboard(records, link_ok=None):
    intro = (
        f"{len(records)} recorded experiment cases, including controls, retired ideas and "
        "blocked runs. Source of truth: `research/registry/experiments.jsonl`; add records "
        "with `scripts/experiments.py log`. **Compare only inside one context.** Rows are "
        "ordered by the frontier of net CAGR (higher) against max drawdown (lower), then by "
        "CAGR; Calmar and Sharpe are diagnostics and no blended score exists. `DD>30%` marks "
        f"drawdown beyond the {DRAWDOWN_TOLERANCE:.0%} mandate reassessment reference; it is a flag, "
        "not a gate. Development rows are viewed history and are not evidence of future "
        "returns; only forward, shadow, paper and live classes escape hindsight. "
        "`imported` rows come from the retired hand-edited table and keep their original "
        "evidence status; context codes and study notes for them are defined in the "
        "[archived hand-edited leaderboard](history/2026-11-09-hand-edited-leaderboard.md).\n")
    out = [_front("Research leaderboard", records, intro)]
    for cls in CLASSES:
        group = [r for r in records if r["evidence_class"] == cls]
        out.append(f"\n## {CLASS_TITLES[cls]}\n")
        if not group:
            out.append("_No records yet._\n")
            continue
        contexts = {}
        for r in group:
            contexts.setdefault((r["context"]["code"], r["context"]["period"]), []).append(r)
        for (code, period), rows in sorted(contexts.items()):
            front = frontier_ids(rows)
            rows = sorted(rows, key=lambda r: (r["record_id"] not in front,
                                              -(r["metrics"].get("net_cagr") if r["metrics"].get("net_cagr") is not None else -9),
                                              r["record_id"]))
            out.append(f"\n### Context {_cell(code)} · {_cell(period)}\n")
            out.append("| Variant | Frontier | Disposition | Net CAGR | Max DD | Underwater (sessions / days) | Calmar | Sharpe | Flags | Outcome | Lesson | Evidence |")
            out.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
            for r in rows:
                m = r["metrics"]
                flags = []
                if m.get("max_drawdown") is not None and m["max_drawdown"] > DRAWDOWN_TOLERANCE:
                    flags.append("DD>30%")
                if r.get("imported"):
                    flags.append("imported")
                flags += [t for t in (r.get("tags") or []) if t in ("negative result", "blocked")]
                out.append("| " + " | ".join([
                    _cell(r["name"]), "yes" if r["record_id"] in front else "no" if m.get("net_cagr") is not None and m.get("max_drawdown") is not None else "unranked",
                    r["disposition"], _pct(m.get("net_cagr")), _pct(m.get("max_drawdown")), _underwater(m),
                    _num(m.get("calmar")), _num(m.get("sharpe"), 3), _cell(", ".join(flags) or "-"),
                    _cell(r.get("outcome") or "-"), _cell(r["lesson"]), _evidence(r, link_ok)]) + " |")
    return "\n".join(out) + "\n"


def render_dead_ends(records, link_ok=None):
    intro = ("Ideas that were retired or blocked, with the lesson recorded, so they are not "
             "repeated without new evidence. Read the context before reusing a lesson: it "
             "applies to that universe, period and cost model.\n")
    rows = [r for r in records if r["disposition"] in ("retire", "blocked")]
    out = [_front("Dead ends and lessons", records, intro)]
    if not rows:
        out.append("_No retired or blocked ideas recorded._\n")
        return "\n".join(out)
    out.append("| Variant | Disposition | Class | Context | Lesson | Evidence |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for r in sorted(rows, key=lambda r: (r["name"].lower(), r["record_id"])):
        out.append("| " + " | ".join([
            _cell(r["name"]), r["disposition"], r["evidence_class"],
            _cell(f"{r['context']['code']} · {r['context']['period']}"), _cell(r["lesson"]),
            _evidence(r, link_ok)]) + " |")
    return "\n".join(out) + "\n"


def learning_curve(records, cls):
    """Steps where the best net CAGR within the drawdown tolerance improved, per class."""
    steps, best, count = [], None, 0
    for r in sorted((r for r in records if r["evidence_class"] == cls),
                    key=lambda r: (r["logged_at"], r["record_id"])):
        count += 1
        m = r["metrics"]
        if m.get("net_cagr") is None or m.get("max_drawdown") is None or m["max_drawdown"] > DRAWDOWN_TOLERANCE:
            continue
        if best is None or m["net_cagr"] > best:
            best = m["net_cagr"]
            steps.append((count, r["logged_at"][:10], r["name"], m["net_cagr"], m["max_drawdown"]))
    return count, steps


def render_learning_curve(records, link_ok=None):
    intro = (
        "Progress over cumulative experiments, per evidence class. A step is a new best net "
        f"CAGR among records with max drawdown within {DRAWDOWN_TOLERANCE:.0%}: a constraint, "
        "not a blended score. **Development steps are partly hindsight** and rise with the "
        "number of trials tried; only a rising sealed-forward, shadow, paper or live curve is "
        "evidence of learning. A flat curve with many experiments is a finding, not a failure "
        "to record.\n")
    out = [_front("Learning curve", records, intro)]
    for cls in CLASSES:
        count, steps = learning_curve(records, cls)
        out.append(f"\n## {CLASS_TITLES[cls]}\n")
        if count == 0:
            out.append("_No records yet._\n")
            continue
        out.append(f"{count} experiments recorded; {len(steps)} improvement step(s).\n")
        if not steps:
            out.append("_No record within the drawdown tolerance has a measured CAGR._\n")
            continue
        out.append("| Experiment # | Logged | Variant | Net CAGR | Max DD |")
        out.append("| --- | --- | --- | --- | --- |")
        for n, day, name, cagr, dd in steps:
            out.append(f"| {n} | {day} | {_cell(name)} | {_pct(cagr)} | {_pct(dd)} |")
    return "\n".join(out) + "\n"


VIEWS = {"leaderboard.md": render_leaderboard, "dead-ends.md": render_dead_ends,
         "learning-curve.md": render_learning_curve}
