"""Artifact catalog: every schema-versioned file the platform reads or writes, with a pure loader,
a source scan for schema ids and a deterministic renderer.

`research/registry/artifacts.json` is the one hand-maintained catalog. The loader validates
shape and vocabularies; `scan_schema_ids` finds the ids that code declares so a check can fail on
an id nobody catalogued. Nothing here writes a file and nothing reads the clock: `updated` is the
registry's own date.
"""
import json
import re
from pathlib import Path

from research.control.incumbents import _cell

SCHEMA = "artifacts/v1"
STAGES = ("intake", "design", "data", "run", "confirm", "diagnose", "validate", "decide", "paper", "views")
LOCATIONS = ("tracked", "local")
AUTHORITIES = ("authoritative", "view")
STATUSES = ("implemented", "planned", "template-only", "frozen-study-specific")
OWNER = "project-maintainers"
GENERATED = "<!-- Generated by scripts/artifacts.py render. Do not edit by hand. -->"
_FIELDS = {"schema_id", "name", "stage", "location", "authority", "producer", "consumers", "retention", "status"}
_TEXT = ("name", "producer", "retention")
_ID = r"[a-z][a-z0-9_.-]*/v\d+"
_ID_RE = re.compile(rf"{_ID}")
_ID_ANY = r"[A-Za-z][A-Za-z0-9_.-]*/v\d+"
_PATH_RE = re.compile(r"[\w./-]+\.(?:py|json|jsonl|md)\b")
REPO_ROOT = Path(__file__).resolve().parents[2]
_DECLARED = (
    re.compile(rf"""\w*SCHEMA\w*\s*(?::\s*\w+)?\s*=\s*["']({_ID_ANY})["']"""),
    re.compile(rf"""\bschema["']?\)?\s*(?:[:=]|[!=]=)\s*["']({_ID_ANY})["']"""),
)


class ArtifactsError(ValueError):
    pass


def _check_paths(item, root):
    for text in [item["producer"], *item["consumers"]]:
        for token in _PATH_RE.findall(text):
            if "/" in token and not (root / token).exists():
                raise ArtifactsError(f"{item['name']}: {token} does not exist")


def _check_entry(item, names, ids):
    if not isinstance(item, dict) or set(item) != _FIELDS:
        raise ArtifactsError(f"bad artifact entry: {item!r}")
    name = item["name"]
    for key in _TEXT:
        if not isinstance(item[key], str) or not item[key].strip():
            raise ArtifactsError(f"{name!r}: {key} must be non-empty text")
    for key, allowed in (("stage", STAGES), ("location", LOCATIONS), ("authority", AUTHORITIES),
                         ("status", STATUSES)):
        if item[key] not in allowed:
            raise ArtifactsError(f"{name}: {key} must be one of {', '.join(allowed)}; got {item[key]!r}")
    consumers = item["consumers"]
    if not isinstance(consumers, list) or not all(isinstance(c, str) and c.strip() for c in consumers):
        raise ArtifactsError(f"{name}: consumers must be a list of text")
    schema_id = item["schema_id"]
    if item["status"] == "template-only":
        if schema_id is not None:
            raise ArtifactsError(f"{name}: a template-only artifact has no schema_id")
    elif not isinstance(schema_id, str) or not _ID_RE.fullmatch(schema_id):
        raise ArtifactsError(f"{name}: schema_id must look like name/vN; got {schema_id!r}")
    if name in names:
        raise ArtifactsError(f"artifact name {name} is declared twice")
    if schema_id is not None and schema_id in ids:
        raise ArtifactsError(f"schema id {schema_id} is declared twice")


def _read(path):
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ArtifactsError(f"artifacts unreadable: {error}") from None
    if (not isinstance(doc, dict) or doc.get("schema") != SCHEMA or set(doc) != {"schema", "updated", "entries"}
            or not isinstance(doc["entries"], list)):
        raise ArtifactsError(f"artifacts must have schema {SCHEMA}, updated and an entries list")
    if not isinstance(doc["updated"], str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", doc["updated"]):
        raise ArtifactsError("updated must be a YYYY-MM-DD date")
    return doc


def load_artifacts(path, root=REPO_ROOT):
    """The validated entries. Raises ArtifactsError on any shape, vocabulary or path problem.

    Path-like tokens (containing `/`, ending .py/.json/.jsonl/.md) in `producer` and `consumers`
    must exist under `root`; pass root=None to skip that check.
    """
    doc = _read(path)
    names, ids = set(), set()
    for item in doc["entries"]:
        _check_entry(item, names, ids)
        if root is not None:
            _check_paths(item, Path(root))
        names.add(item["name"])
        if item["schema_id"] is not None:
            ids.add(item["schema_id"])
    return doc["entries"]


def load_updated(path):
    """The registry's own `updated` date (the generated document's date; never the clock)."""
    return _read(path)["updated"]


def scan_schema_ids(roots):
    """id -> sorted files declaring it, over `.py` files under the existing roots.

    Matches `SCHEMA = "x/vN"` (either quote style, any `*SCHEMA*` name) and `"schema": "x/vN"`,
    `schema="x/vN"` and `get("schema") == "x/vN"` literals. Paths are relative to each root's parent.
    """
    found = {}
    for root in roots:
        root = Path(root)
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*.py")):
            text = path.read_text(encoding="utf-8", errors="replace")
            rel = path.relative_to(root.parent).as_posix()
            for pattern in _DECLARED:
                for ident in pattern.findall(text):
                    files = found.setdefault(ident, [])
                    if rel not in files:
                        files.append(rel)
    return {ident: sorted(files) for ident, files in sorted(found.items())}


def render_markdown(entries, updated):
    """The `docs/artifacts.md` text, grouped by stage in STAGES order. Pure and deterministic."""
    out = [f"---\nstatus: active\nupdated: {updated}\nowner: {OWNER}\n---\n\n"
           f"# Artifact catalog\n\n{GENERATED}\n\n"
           "Every schema-versioned artifact the platform reads or writes, grouped by research stage "
           f"and kept in `research/registry/artifacts.json` (updated {updated}). "
           "`scripts/artifacts.py check` fails when code declares a schema id that is not listed here "
           "or when a producer or consumer path does not exist. "
           "Ids that appear only in closed-study evidence under `docs/tasks/evidence` are not catalogued.\n",
           "Authority is `authoritative` for the source of truth and `view` for a derived rendering. "
           "Status is `implemented`, `planned` (named by the plan that will build it), `template-only` "
           "(a fill-in file with no schema id) or `frozen-study-specific` (a one-study format kept only "
           "so old evidence stays readable).\n"]
    for stage in STAGES:
        rows = sorted((e for e in entries if e["stage"] == stage), key=lambda e: (e["name"], e["schema_id"] or ""))
        if not rows:
            continue
        out += [f"## {stage}\n",
                "| Name | Schema id | Location | Authority | Status | Producer | Consumers | Retention |",
                "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for e in rows:
            schema = f"`{e['schema_id']}`" if e["schema_id"] else "none"
            out.append("| " + " | ".join([
                _cell(e["name"]), _cell(schema), e["location"], e["authority"], e["status"],
                _cell(e["producer"]), _cell(", ".join(e["consumers"]) or "none"), _cell(e["retention"])]) + " |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"
