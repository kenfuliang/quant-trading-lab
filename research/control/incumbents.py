"""Incumbent declarations per pipeline stage and the generated pipeline status document.

`research/registry/incumbents.json` is the one hand-maintained declaration of which algorithm
is in use at each stage. It changes only when a closed research cycle changes the incumbent,
and each entry cites the experiment record that justified it. The status document is a pure
render of that file plus the registry and the stage view model, so it is deterministic and a
stale copy is detectable by string comparison. Nothing here writes a file.
"""
import json
from pathlib import Path

from research.control.registry_views import _cell, updated_date
from research.control.stage_map import STAGES

SCHEMA = "incumbents/v1"
AVAILABILITY = ("implemented", "unverified", "blocked", "planned")
_FIELDS = {"stage", "algorithm", "identity", "justified_by", "availability", "last_changed", "scope"}
OWNER = "project-maintainers"


class IncumbentsError(ValueError):
    pass


def _check_last_changed(stage, value):
    if value is None:
        return
    if (not isinstance(value, dict) or set(value) != {"cycle_id", "date"}
            or not all(isinstance(v, str) and v for v in value.values())):
        raise IncumbentsError(f"{stage}: last_changed must be null or {{cycle_id, date}} text")


def load_incumbents(path, record_ids):
    """Entries keyed by stage. Raises IncumbentsError on any shape or reference problem."""
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise IncumbentsError(f"incumbents unreadable: {error}") from None
    if not isinstance(doc, dict) or doc.get("schema") != SCHEMA or not isinstance(doc.get("incumbents"), list):
        raise IncumbentsError(f"incumbents must have schema {SCHEMA} and an incumbents list")
    loaded = {}
    for item in doc["incumbents"]:
        if not isinstance(item, dict) or set(item) != _FIELDS:
            raise IncumbentsError(f"bad incumbent entry: {item!r}")
        stage = item["stage"]
        if stage not in STAGES:
            raise IncumbentsError(f"unknown stage {stage!r}")
        if stage in loaded:
            raise IncumbentsError(f"stage {stage} is declared twice")
        if item["availability"] not in AVAILABILITY:
            raise IncumbentsError(f"{stage}: availability must be one of {', '.join(AVAILABILITY)}")
        for key in ("algorithm", "identity", "scope"):
            if not isinstance(item[key], str) or not item[key].strip():
                raise IncumbentsError(f"{stage}: {key} must be non-empty text")
        justified = item["justified_by"]
        if justified is None and item["algorithm"] != "none":
            raise IncumbentsError(f"{stage}: justified_by is required unless the algorithm is none")
        if justified is not None and justified not in record_ids:
            raise IncumbentsError(f"{stage}: justified_by names unknown record {justified}")
        _check_last_changed(stage, item["last_changed"])
        loaded[stage] = item
    return loaded


def _points(value):
    return "n/a" if value is None else f"{value * 100:+.2f}"


def _latest_result(cell, records_by_id):
    matched = [p for p in cell["pairs"] if p["status"] == "matched"]
    if matched:
        latest = max(matched, key=lambda p: (records_by_id[p["challenger"]]["logged_at"], p["challenger"]))
        delta = latest["delta"]
        return (f"{latest['effect']}, {latest['disposition']}: net CAGR {_points(delta['net_cagr'])} pt, "
                f"max DD {_points(delta['max_drawdown'])} pt")
    return "no matched control" if cell["records"] else "no evidence"


def render_status(records, incumbents, model):
    """The `docs/pipeline-status.md` text: one row per stage in STAGES order."""
    by_id = {r["record_id"]: r for r in records}
    intro = ("Which algorithm is in use at each pipeline stage, and what the registry shows against "
             "its matched control. **Generated; do not edit by hand.** Declared in "
             "`research/registry/incumbents.json`; classified in `research/registry/stage-map.json`; "
             "evidence in `research/registry/experiments.jsonl`. A stage with no declaration reads "
             "`undeclared`; an unreviewed record is not counted in any stage. Effects use net CAGR "
             "(higher) against max drawdown (lower) only, per matched pair, in percentage points; "
             "development evidence is viewed history and no row is an adoption verdict.\n")
    out = [f"---\nstatus: active\nupdated: {updated_date(records)}\nowner: {OWNER}\n---\n\n"
           f"# Pipeline status\n\n<!-- Generated by scripts/stages.py render. Do not edit by hand. -->\n\n{intro}",
           "| Stage | Algorithm in use | Availability | Latest paired result | Records | Scope |",
           "| --- | --- | --- | --- | --- | --- |"]
    for stage in STAGES:
        declared = incumbents.get(stage)
        cell = model["stages"][stage]
        out.append("| " + " | ".join([
            stage,
            _cell(declared["algorithm"]) if declared else "undeclared",
            declared["availability"] if declared else "-",
            _cell(_latest_result(cell, by_id)),
            str(len(cell["records"])),
            _cell(declared["scope"]) if declared else "-"]) + " |")
    return "\n".join(out) + "\n"
