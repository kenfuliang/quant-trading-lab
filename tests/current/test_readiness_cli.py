import contextlib
import io
import json
from pathlib import Path
import tempfile
import unittest

from scripts import readiness as cli

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "research/registry/readiness.json"


def run(*argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = cli.main(list(argv))
    return code, out.getvalue(), err.getvalue()


class ReadinessCliTests(unittest.TestCase):
    def test_render_then_check_passes(self):
        with tempfile.TemporaryDirectory() as t:
            doc = Path(t) / "readiness-checklist.md"
            self.assertEqual(run("--doc", str(doc), "render")[0], 0)
            self.assertIn("Generated by scripts/readiness.py render", doc.read_text(encoding="utf-8"))
            code, out, err = run("--doc", str(doc), "check")
            self.assertEqual((code, err), (0, ""), err)

    def test_check_fails_on_stale_or_hand_edited_doc(self):
        with tempfile.TemporaryDirectory() as t:
            doc = Path(t) / "readiness-checklist.md"
            run("--doc", str(doc), "render")
            doc.write_text(doc.read_text(encoding="utf-8") + "\nhand edit\n", encoding="utf-8")
            code, _, err = run("--doc", str(doc), "check")
            self.assertEqual(code, 1)
            self.assertIn(f"error: {doc} is stale; run scripts/readiness.py render", err)
            doc.unlink()
            code, _, err = run("--doc", str(doc), "check")
            self.assertEqual(code, 1)
            self.assertIn("is stale", err)

    def test_check_fails_on_missing_evidence(self):
        with tempfile.TemporaryDirectory() as t:
            data = json.loads(REGISTRY.read_text(encoding="utf-8"))
            data["aspects"][0]["evidence"] = ["docs/does-not-exist.md"]
            registry = Path(t) / "readiness.json"
            registry.write_text(json.dumps(data), encoding="utf-8")
            doc = Path(t) / "doc.md"
            code, _, err = run("--registry", str(registry), "--doc", str(doc), "check")
            self.assertEqual(code, 1)
            self.assertIn("does-not-exist.md", err)
            code, _, err = run("--registry", str(registry), "--doc", str(doc), "render")
            self.assertEqual(code, 1)
            self.assertFalse(doc.exists())

    def test_build_writes_page(self):
        with tempfile.TemporaryDirectory() as t:
            code, out, _ = run("build", "--dir", t)
            self.assertEqual(code, 0)
            page = (Path(t) / "readiness.html").read_text(encoding="utf-8")
            self.assertTrue(page.lstrip().lower().startswith("<!doctype html>"))

    def test_committed_doc_is_current(self):
        self.assertEqual(run("check")[0], 0)


if __name__ == "__main__":
    unittest.main()
