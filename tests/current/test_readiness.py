"""Readiness registry: loader validation, scoring arithmetic and deterministic renderers."""
import copy
import datetime
import json
import tempfile
import unittest
from pathlib import Path

from research.control import readiness
from research.control.readiness import (
    AREAS, ReadinessError, area_scores, fix_first, load_readiness, render_markdown, render_page)

ROOT = Path(__file__).resolve().parents[2]
GATES = {"G0", "G0.1", "G3", "G3.2"}


def aspect(**over):
    base = {"id": "D1", "area": "Data", "aspect": "Acquisition", "score": 3, "importance": "H",
            "critique": "works", "next_action": "keep", "roadmap_step": None,
            "evidence": ["docs/goals.md"], "gates": ["G0.1"]}
    base.update(over)
    return base


def document(*aspects):
    return {"schema": "readiness/v1", "assessed": "2026-11-17", "aspects": list(aspects)}


class ReadinessTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        (self.root / "docs").mkdir()
        (self.root / "docs" / "goals.md").write_text("x", encoding="utf-8")

    def load(self, doc):
        path = self.root / "readiness.json"
        path.write_text(json.dumps(doc), encoding="utf-8")
        return load_readiness(path, GATES, self.root)

    def test_rejects_bad_score_importance_area_gate_and_missing_evidence(self):
        cases = {
            "score 5.5": aspect(score=5.5),
            "score 2.3": aspect(score=2.3),
            "importance X": aspect(importance="X"),
            "unknown area": aspect(area="Elsewhere"),
            "gate G9.99": aspect(gates=["G9.99"]),
            "missing evidence": aspect(evidence=["docs/nope.md"]),
            "no evidence but high score": aspect(evidence=[], score=2),
            "id lowercase": aspect(id="d1"),
            "id without digits": aspect(id="D"),
            "id with suffix": aspect(id="D1a"),
        }
        for name, bad in cases.items():
            with self.subTest(name):
                with self.assertRaises(ReadinessError):
                    self.load(document(bad))
        with self.subTest("duplicate id"):
            with self.assertRaises(ReadinessError):
                self.load(document(aspect(), aspect()))
        with self.subTest("valid"):
            self.assertEqual(len(self.load(document(aspect(), aspect(id="D2", evidence=[], score=1)))["aspects"]), 2)

    def test_fix_first_is_high_importance_score_at_most_two_sorted(self):
        doc = self.load(document(
            aspect(id="D3", score=2), aspect(id="D1", score=1, evidence=[]),
            aspect(id="D2", score=1, evidence=[]), aspect(id="D4", score=2.5),
            aspect(id="D5", score=1, importance="M", evidence=[]), aspect(id="D6", score=0.5, evidence=[])))
        self.assertEqual([a["id"] for a in fix_first(doc)], ["D6", "D1", "D2", "D3"])

    def test_weighted_average_uses_3_2_1(self):
        doc = self.load(document(
            aspect(id="D1", score=4, importance="H"), aspect(id="D2", score=2, importance="M"),
            aspect(id="D3", score=1, importance="L"),
            aspect(id="R1", area="Research and evaluation", score=3, importance="L")))
        scores = area_scores(doc)
        self.assertAlmostEqual(scores["Data"][0], 7 / 3)
        self.assertAlmostEqual(scores["Data"][1], (12 + 4 + 1) / 6)
        self.assertEqual(scores["Research and evaluation"], (3, 3))
        self.assertAlmostEqual(scores["Overall"][0], 10 / 4)
        self.assertAlmostEqual(scores["Overall"][1], (12 + 4 + 1 + 3) / 7)
        self.assertNotIn("Engineering", scores)

    def test_markdown_is_deterministic_has_frontmatter_rubric_and_generated_comment(self):
        doc = self.load(document(aspect(id="D2", score=1, evidence=[]), aspect()))
        text = render_markdown(doc)
        self.assertEqual(text, render_markdown(copy.deepcopy(doc)))
        self.assertTrue(text.startswith("---\nstatus: active\nupdated: 2026-11-17\nowner: project-maintainers\n---\n"))
        self.assertIn("<!-- Generated by scripts/readiness.py render. Do not edit by hand. -->", text)
        for line in ("0 absent", "1 ad hoc or one-off", "2 partial", "3 works for the current scope",
                     "4 robust and tested", "5 production-grade"):
            self.assertIn(line, text)
        self.assertIn("Fix first", text)
        self.assertIn("Overall", text)
        table = text[text.index("## All aspects"):]
        self.assertLess(table.index("| D1 |"), table.index("| D2 |"))

    def test_markup_and_pipes_are_neutralised_in_markdown_and_page(self):
        doc = self.load(document(aspect(critique="a | b <script>alert(1)</script>\nnext",
                                        next_action='<img src=x onerror="y">')))
        text = render_markdown(doc)
        self.assertNotIn("<script>", text)
        self.assertNotIn("<img", text)
        self.assertIn("a / b &lt;script&gt;", text)
        page = render_page(doc, "2026-11-17T00:00:00Z")
        self.assertTrue(page.lstrip().lower().startswith("<!doctype html>"))
        self.assertNotIn("<script>", page)
        self.assertNotIn("<img", page)
        self.assertIn("&lt;script&gt;", page)
        self.assertIn("2026-11-17T00:00:00Z", page)

    def test_real_registry_loads(self):
        gates = json.loads((ROOT / "research/registry/gates.json").read_text(encoding="utf-8"))
        ids = set()
        for gate in gates["gates"]:
            ids.add(gate["id"])
            ids.update(item["id"] for item in gate["items"])
        doc = load_readiness(ROOT / "research/registry/readiness.json", ids, ROOT)
        self.assertRegex(doc["assessed"], r"^\d{4}-\d{2}-\d{2}$")
        datetime.date.fromisoformat(doc["assessed"])
        for area in AREAS:
            self.assertTrue([a for a in doc["aspects"] if a["area"] == area], f"no aspect in {area}")
        self.assertEqual(readiness.SCHEMA, "readiness/v1")


if __name__ == "__main__":
    unittest.main()
